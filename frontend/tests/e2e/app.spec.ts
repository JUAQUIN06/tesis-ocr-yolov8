test('PDF real multipágina, zoom, rotación y evaluación pendiente', async ({ page, request }) => {
  await page.route('**/api/analyze', (route) => route.fulfill({ json: recognitionFixture(2) }))
  for (const asset of ['standard_fonts/LiberationSans-Regular.ttf', 'cmaps/Adobe-GB1-0.bcmap', 'wasm/openjpeg.wasm']) {
    const response = await request.get(`/pdfjs/${asset}`)
    expect(response.ok()).toBe(true)
    expect(response.headers()['content-type']).not.toContain('text/html')
    expect((await response.body()).length).toBeGreaterThan(100)
  }
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  const pdf = new jsPDF()
  pdf.text('Curriculum de prueba - pagina uno', 20, 20)
  pdf.addPage()
  pdf.text('Experiencia - pagina dos', 20, 20)
  await page.getByLabel('Seleccionar CV', { exact: true }).setInputFiles({ name: 'cv-real.pdf', mimeType: 'application/pdf', buffer: Buffer.from(pdf.output('arraybuffer')) })
  await expect(page.getByText('Páginas: 2', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Vista previa rápida' }).click()
  await expect(page.getByRole('img', { name: 'Página 1 del documento PDF' })).toBeVisible()
  await expect(page.getByText('Cargando página…')).toHaveCount(0)
  const canvas = page.locator('canvas')
  const originalWidth = await canvas.getAttribute('width')
  await page.getByRole('button', { name: 'Aumentar zoom' }).click()
  await expect(canvas).not.toHaveAttribute('width', originalWidth!)
  await page.getByRole('button', { name: 'Página siguiente' }).click()
  await expect(page.getByRole('img', { name: 'Página 2 del documento PDF' })).toBeVisible()
  await page.getByRole('button', { name: 'Rotar documento' }).click()
  await expect.poll(async () => canvas.evaluate((element: HTMLCanvasElement) => element.width > element.height)).toBe(true)
  await page.getByRole('button', { name: 'Cerrar ventana' }).click()
  await page.getByRole('button', { name: 'Evaluar CV', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'ESTADO INDETERMINADO' })).toBeVisible()
  await expect(page.locator('.score-ring strong')).toHaveText('0%')
  await expect(page.getByText('Reconocimiento real · Dictamen manual')).toBeVisible()
  expect(errors).toEqual([])
})

test('rechazo de archivos inválidos y vista de imagen real', async ({ page }) => {
  await page.getByLabel('Seleccionar CV', { exact: true }).setInputFiles({ name: 'mal.pdf', mimeType: 'application/pdf', buffer: Buffer.from('no soy pdf') })
  await expect(page.getByRole('alert')).toContainText('PDF válido')
  await page.getByLabel('Seleccionar CV', { exact: true }).setInputFiles({ name: 'grande.png', mimeType: 'image/png', buffer: Buffer.alloc(15 * 1024 * 1024 + 1) })
  await expect(page.getByRole('alert')).toContainText('15 MB')
  const image = await page.screenshot()
  await page.getByLabel('Zona de carga de CV').evaluate((element, encoded) => {
    const bytes = Uint8Array.from(atob(encoded), (character) => character.charCodeAt(0))
    const transfer = new DataTransfer()
    transfer.items.add(new File([bytes], 'cv-imagen.png', { type: 'image/png' }))
    element.dispatchEvent(new DragEvent('drop', { bubbles: true, cancelable: true, dataTransfer: transfer }))
  }, image.toString('base64'))
  await expect(page.getByText('cv-imagen.png', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Vista previa rápida' }).click()
  const preview = page.getByRole('img', { name: 'Currículum: cv-imagen.png' })
  await expect(preview).toBeVisible()
  expect(await preview.evaluate((element: HTMLImageElement) => element.naturalWidth)).toBeGreaterThan(0)
  await page.getByRole('button', { name: 'Rotar documento' }).click()
  await expect(page.locator('.rotation-content')).toHaveCSS('transform', /matrix\(0, 1, -1, 0,/)
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
})

