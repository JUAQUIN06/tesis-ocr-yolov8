test('flujo demo, decisiones coherentes, reporte real y navegación SPA', async ({ page, context }) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.evaluate(() => { Object.assign(window, { spaMarker: 'same-document' }) })
  await page.getByRole('button', { name: 'Evaluar CV', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'RESULTADOS DE EVALUACIÓN', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'CUMPLE CON LOS REQUISITOS', exact: true })).toBeVisible()
  await expect(page.locator('.score-ring strong')).toHaveText('67%')
  await page.getByRole('button', { name: 'Aprobar Manualmente' }).click()
  await expect(page.locator('.score-ring strong')).toHaveText('100%')
  await page.getByLabel('Dictamen de Secundaria completa').selectOption('fail')
  await expect(page.getByRole('heading', { name: 'NO CUMPLE CON LOS REQUISITOS' })).toBeVisible()
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.getByRole('button', { name: 'Copiar Dictamen' }).click()
  await expect.poll(() => page.evaluate(() => navigator.clipboard.readText())).toContain('NO CUMPLE CON LOS REQUISITOS')
  await page.getByRole('button', { name: 'No cumple', exact: true }).click()
  await expect(page.locator('.criterion-card')).toHaveCount(1)
  await page.getByRole('button', { name: 'Todos', exact: true }).click()
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Exportar Reporte' }).click()
  const download = await downloadPromise
  expect(download.suggestedFilename()).toMatch(/^Dictamen_.*\.pdf$/)
  const stream = await download.createReadStream()
  const chunks: Buffer[] = []
  for await (const chunk of stream!) chunks.push(Buffer.from(chunk))
  expect(Buffer.concat(chunks).subarray(0, 5).toString()).toBe('%PDF-')
  await page.getByRole('button', { name: 'Modificar filtros' }).click()
  await expect(page.getByRole('heading', { name: 'Filtros de preselección' })).toBeVisible()
  expect(await page.evaluate(() => (window as Window & { spaMarker?: string }).spaMarker)).toBe('same-document')
  await page.goBack()
  await expect(page.getByRole('heading', { name: 'NO CUMPLE CON LOS REQUISITOS' })).toBeVisible()
  expect(errors).toEqual([])
})

